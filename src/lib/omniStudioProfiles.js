export function omniStudioProfileFor(id){return OMNI_STUDIO_PROFILES[id]||null;}
export function omniStudioDraftFor(product){
 const p=omniStudioProfileFor(product?.id);
 if(!p?.settings)return null;
 return {
  machine_type:"xtool_omni",machine_model:"xTool O1 Omni Dual-UV",
  machine_configuration:"Dual UV (not UV + DT fabric)",
  operation:product.operation,material_name:product.name,
  material_notes:product.steps.join("\n")+"\n\nSTUDIO TEST MATRIX:\n"+p.matrix.map((s,i)=>String(i+1)+". "+s).join("\n"),
  source_type:["slate","acrylic"].includes(product.id)?"manufacturer":"manual",
  source_url:product.source,
  safety_notes:product.primer+"; "+product.accessory+"; "+p.note,
  settings:{...p.settings,recipe_evidence:"research candidate only; not physically validated",product_library_id:product.id,
    settings_sources:[...new Set(p.fields.map(f=>f.source))],
    settings_provenance:p.fields.map(({label,value,evidence,source})=>({label,value,evidence,source}))}
 };
}
