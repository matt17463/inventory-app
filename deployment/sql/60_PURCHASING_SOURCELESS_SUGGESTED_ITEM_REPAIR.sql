-- Skilled Crafting Inventory App v1.4.8
-- Purchasing source-less suggested-item repair
--
-- Extends v1.4.7 so a Purchasing recommendation can be corrected even when
-- there is no usable order / pull-sheet source row to repair.
--
-- Supported source-less drivers:
--   * active reservations that are not tied to an existing job_item
--   * low-stock threshold / shelf-stock recommendations
--   * a durable Purchasing replacement rule for future operator guidance
--
-- IMPORTANT SAFETY BOUNDARIES:
--   * does NOT move or deduct physical on-hand inventory
--   * does NOT create inventory movements
--   * does NOT rewrite WooCommerce product mappings
--   * does NOT bulk-repair existing pull-sheet lines; v1.4.7 Fix Pairing remains
--     the correct tool for source rows with a job_item_id
--   * active reservations tied to inactive/closed job items are left unchanged
--
-- SAFE TO RERUN.

begin;

set local lock_timeout = '5s';
set local statement_timeout = '120s';

-- ---------------------------------------------------------------------------
-- Preflight
-- ---------------------------------------------------------------------------
do $guard$
begin
  if to_regclass('public.blank_products') is null then
    raise exception 'Required table public.blank_products is missing.';
  end if;

  if to_regclass('public.inventory_reservations') is null then
    raise exception 'Required table public.inventory_reservations is missing.';
  end if;

  if to_regclass('public.job_items') is null then
    raise exception 'Required table public.job_items is missing.';
  end if;

  if to_regclass('public.purchasing_recommended_orders') is null then
    raise exception 'Required view public.purchasing_recommended_orders is missing.';
  end if;

  if not exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'blank_products'
      and column_name = 'low_stock_threshold'
  ) then
    raise exception 'blank_products.low_stock_threshold is required for source-less threshold repair.';
  end if;

  if not exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'inventory_reservations'
      and column_name = 'blank_product_id'
  ) then
    raise exception 'inventory_reservations.blank_product_id is required.';
  end if;

  if to_regprocedure('public.sc_purchasing_status_is_active_v1(text)') is null then
    raise exception 'Purchasing active-status helper is missing. Install the Purchasing reservation recount fix first.';
  end if;

  if to_regprocedure('public.sc_purchasing_json_numeric_v1(jsonb,text[])') is null then
    raise exception 'Purchasing numeric JSON helper is missing. Install the Purchasing reservation recount fix first.';
  end if;

  if to_regprocedure('public.sc_purchasing_json_text_v1(jsonb,text[])') is null then
    raise exception 'Purchasing text JSON helper is missing. Install the Purchasing reservation recount fix first.';
  end if;
end
$guard$;

-- ---------------------------------------------------------------------------
-- Durable Purchasing-only replacement preference.
--
-- This deliberately does not masquerade as a WooCommerce mapping. It is used
-- only for source-less Purchasing suggestions where no Woo variation/SKU/order
-- identity exists to save through sc_set_product_blank_mapping_v1().
-- ---------------------------------------------------------------------------
create table if not exists public.sc_purchasing_blank_replacement_rules (
  id bigint generated by default as identity primary key,
  source_blank_product_id uuid not null references public.blank_products(id),
  replacement_blank_product_id uuid not null references public.blank_products(id),
  reason text,
  active boolean not null default true,
  actor_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint sc_purchasing_blank_replacement_rule_different_blank
    check (source_blank_product_id <> replacement_blank_product_id)
);

create unique index if not exists sc_purchasing_blank_replacement_rules_one_active_source_idx
  on public.sc_purchasing_blank_replacement_rules(source_blank_product_id)
  where active;

create index if not exists sc_purchasing_blank_replacement_rules_target_idx
  on public.sc_purchasing_blank_replacement_rules(replacement_blank_product_id)
  where active;

alter table public.sc_purchasing_blank_replacement_rules enable row level security;

-- ---------------------------------------------------------------------------
-- Audit log. This records what the row-level repair changed without fabricating
-- an inventory movement.
-- ---------------------------------------------------------------------------
create table if not exists public.sc_purchasing_row_repair_log (
  id bigint generated by default as identity primary key,
  source_blank_product_id uuid not null references public.blank_products(id),
  replacement_blank_product_id uuid not null references public.blank_products(id),
  repair_kind text not null default 'source_less_suggestion',
  unlinked_reservations_moved integer not null default 0,
  unlinked_reserved_quantity_moved numeric not null default 0,
  linked_active_job_items_detected integer not null default 0,
  inactive_linked_reservations_skipped integer not null default 0,
  source_threshold_before numeric,
  source_threshold_after numeric,
  replacement_threshold_before numeric,
  replacement_threshold_after numeric,
  threshold_moved boolean not null default false,
  replacement_rule_id bigint references public.sc_purchasing_blank_replacement_rules(id),
  reason text,
  actor_id uuid,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists sc_purchasing_row_repair_log_source_idx
  on public.sc_purchasing_row_repair_log(source_blank_product_id, created_at desc);

alter table public.sc_purchasing_row_repair_log enable row level security;

-- ---------------------------------------------------------------------------
-- Preview RPC
-- ---------------------------------------------------------------------------
drop function if exists public.sc_purchasing_suggested_item_preview_v1(uuid);

create or replace function public.sc_purchasing_suggested_item_preview_v1(
  p_source_blank_product_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_source jsonb;
  v_report jsonb;
  v_source_threshold numeric := 0;
  v_active_reservation_count integer := 0;
  v_active_reserved_quantity numeric := 0;
  v_unlinked_count integer := 0;
  v_unlinked_quantity numeric := 0;
  v_linked_active_job_item_count integer := 0;
  v_inactive_linked_count integer := 0;
  v_rule record;
begin
  if p_source_blank_product_id is null then
    raise exception 'A suggested blank product is required.';
  end if;

  select to_jsonb(bp)
    into v_source
  from public.blank_products bp
  where bp.id = p_source_blank_product_id;

  if v_source is null then
    raise exception 'Suggested blank product % was not found.', p_source_blank_product_id;
  end if;

  v_source_threshold := coalesce(nullif(v_source->>'low_stock_threshold', '')::numeric, 0);

  select to_jsonb(r)
    into v_report
  from public.purchasing_recommended_orders r
  where r.blank_product_id = p_source_blank_product_id
  limit 1;

  with reservation_rows as (
    select
      r.id::text as reservation_id,
      coalesce(
        public.sc_purchasing_json_numeric_v1(to_jsonb(r), 'quantity', 'reserved_quantity'),
        0
      ) as quantity,
      public.sc_purchasing_json_numeric_v1(to_jsonb(r), 'job_item_id')::bigint as job_item_id,
      public.sc_purchasing_json_text_v1(to_jsonb(r), 'status') as reservation_status
    from public.inventory_reservations r
    where r.blank_product_id = p_source_blank_product_id
      and public.sc_purchasing_status_is_active_v1(
        public.sc_purchasing_json_text_v1(to_jsonb(r), 'status')
      )
  ), classified as (
    select
      rr.*,
      ji.id as joined_job_item_id,
      public.sc_purchasing_status_is_active_v1(
        public.sc_purchasing_json_text_v1(to_jsonb(ji), 'status')
      ) as job_item_active
    from reservation_rows rr
    left join public.job_items ji on ji.id = rr.job_item_id
  )
  select
    count(*)::integer,
    coalesce(sum(quantity), 0)::numeric,
    count(*) filter (where job_item_id is null or joined_job_item_id is null)::integer,
    coalesce(sum(quantity) filter (where job_item_id is null or joined_job_item_id is null), 0)::numeric,
    count(distinct job_item_id) filter (
      where joined_job_item_id is not null and job_item_active
    )::integer,
    count(*) filter (
      where joined_job_item_id is not null and not job_item_active
    )::integer
  into
    v_active_reservation_count,
    v_active_reserved_quantity,
    v_unlinked_count,
    v_unlinked_quantity,
    v_linked_active_job_item_count,
    v_inactive_linked_count
  from classified;

  select
    rule.id,
    rule.replacement_blank_product_id,
    replacement.sku_base,
    replacement.name
  into v_rule
  from public.sc_purchasing_blank_replacement_rules rule
  join public.blank_products replacement
    on replacement.id = rule.replacement_blank_product_id
  where rule.source_blank_product_id = p_source_blank_product_id
    and rule.active
  order by rule.id desc
  limit 1;

  return jsonb_build_object(
    'success', true,
    'source_blank_product_id', p_source_blank_product_id,
    'source_sku', v_source->>'sku_base',
    'source_name', v_source->>'name',
    'source_threshold', v_source_threshold,
    'report_row', coalesce(v_report, '{}'::jsonb),
    'active_reservation_count', v_active_reservation_count,
    'active_reserved_quantity', v_active_reserved_quantity,
    'unlinked_active_reservation_count', v_unlinked_count,
    'unlinked_active_reserved_quantity', v_unlinked_quantity,
    'linked_active_job_item_count', v_linked_active_job_item_count,
    'inactive_linked_reservation_count', v_inactive_linked_count,
    'saved_rule_id', v_rule.id,
    'saved_replacement_blank_product_id', v_rule.replacement_blank_product_id,
    'saved_replacement_sku', v_rule.sku_base,
    'saved_replacement_name', v_rule.name
  );
end;
$$;

grant execute on function public.sc_purchasing_suggested_item_preview_v1(uuid)
  to anon, authenticated;

-- ---------------------------------------------------------------------------
-- Repair RPC
-- ---------------------------------------------------------------------------
drop function if exists public.sc_purchasing_fix_suggested_item_v1(uuid, uuid, text, boolean, boolean, boolean);

create or replace function public.sc_purchasing_fix_suggested_item_v1(
  p_source_blank_product_id uuid,
  p_new_blank_product_id uuid,
  p_reason text default 'Corrected source-less Purchasing suggestion',
  p_move_unlinked_reservations boolean default true,
  p_move_threshold boolean default true,
  p_remember_rule boolean default true
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_source_threshold numeric := 0;
  v_target_threshold numeric := 0;
  v_target_threshold_after numeric := 0;
  v_reason text;
  v_actor_id uuid;
  v_unlinked_ids text[] := array[]::text[];
  v_unlinked_count integer := 0;
  v_unlinked_quantity numeric := 0;
  v_linked_active_job_item_count integer := 0;
  v_inactive_linked_count integer := 0;
  v_threshold_moved boolean := false;
  v_rule_id bigint := null;
  v_audit_id bigint;
begin
  if p_source_blank_product_id is null then
    raise exception 'A suggested blank product is required.';
  end if;

  if p_new_blank_product_id is null then
    raise exception 'Choose a replacement blank product.';
  end if;

  if p_source_blank_product_id = p_new_blank_product_id then
    raise exception 'Choose a different replacement blank product.';
  end if;

  if not coalesce(p_move_unlinked_reservations, false)
     and not coalesce(p_move_threshold, false)
     and not coalesce(p_remember_rule, false) then
    raise exception 'Select at least one correction action.';
  end if;

  v_reason := coalesce(nullif(btrim(p_reason), ''), 'Corrected source-less Purchasing suggestion');

  begin
    v_actor_id := auth.uid();
  exception when others then
    v_actor_id := null;
  end;

  select coalesce(bp.low_stock_threshold, 0)::numeric
    into v_source_threshold
  from public.blank_products bp
  where bp.id = p_source_blank_product_id
    and coalesce(bp.sc_is_archived, false) = false
  for update;

  if not found then
    raise exception 'The currently suggested blank does not exist or is archived.';
  end if;

  select coalesce(bp.low_stock_threshold, 0)::numeric
    into v_target_threshold
  from public.blank_products bp
  where bp.id = p_new_blank_product_id
    and coalesce(bp.sc_is_archived, false) = false
  for update;

  if not found then
    raise exception 'The replacement blank does not exist or is archived.';
  end if;

  -- Classify active reservations before changing anything. Only reservations
  -- with no existing job_item are eligible for direct source-less repair.
  with reservation_rows as (
    select
      r.id::text as reservation_id,
      coalesce(
        public.sc_purchasing_json_numeric_v1(to_jsonb(r), 'quantity', 'reserved_quantity'),
        0
      ) as quantity,
      public.sc_purchasing_json_numeric_v1(to_jsonb(r), 'job_item_id')::bigint as job_item_id
    from public.inventory_reservations r
    where r.blank_product_id = p_source_blank_product_id
      and public.sc_purchasing_status_is_active_v1(
        public.sc_purchasing_json_text_v1(to_jsonb(r), 'status')
      )
  ), classified as (
    select
      rr.*,
      ji.id as joined_job_item_id,
      public.sc_purchasing_status_is_active_v1(
        public.sc_purchasing_json_text_v1(to_jsonb(ji), 'status')
      ) as job_item_active
    from reservation_rows rr
    left join public.job_items ji on ji.id = rr.job_item_id
  )
  select
    coalesce(array_agg(reservation_id) filter (
      where job_item_id is null or joined_job_item_id is null
    ), array[]::text[]),
    count(*) filter (
      where job_item_id is null or joined_job_item_id is null
    )::integer,
    coalesce(sum(quantity) filter (
      where job_item_id is null or joined_job_item_id is null
    ), 0)::numeric,
    count(distinct job_item_id) filter (
      where joined_job_item_id is not null and job_item_active
    )::integer,
    count(*) filter (
      where joined_job_item_id is not null and not job_item_active
    )::integer
  into
    v_unlinked_ids,
    v_unlinked_count,
    v_unlinked_quantity,
    v_linked_active_job_item_count,
    v_inactive_linked_count
  from classified;

  if coalesce(p_move_unlinked_reservations, false)
     and coalesce(array_length(v_unlinked_ids, 1), 0) > 0 then
    update public.inventory_reservations r
       set blank_product_id = p_new_blank_product_id
     where r.id::text = any(v_unlinked_ids)
       and r.blank_product_id = p_source_blank_product_id
       and public.sc_purchasing_status_is_active_v1(
         public.sc_purchasing_json_text_v1(to_jsonb(r), 'status')
       );
  else
    -- Report what was actually moved, not merely what was detected.
    v_unlinked_count := 0;
    v_unlinked_quantity := 0;
  end if;

  v_target_threshold_after := v_target_threshold;

  if coalesce(p_move_threshold, false) and v_source_threshold > 0 then
    v_target_threshold_after := greatest(v_target_threshold, v_source_threshold);

    update public.blank_products
       set low_stock_threshold = v_target_threshold_after
     where id = p_new_blank_product_id;

    update public.blank_products
       set low_stock_threshold = 0
     where id = p_source_blank_product_id;

    v_threshold_moved := true;
  end if;

  if coalesce(p_remember_rule, false) then
    update public.sc_purchasing_blank_replacement_rules
       set active = false,
           updated_at = now()
     where source_blank_product_id = p_source_blank_product_id
       and active;

    insert into public.sc_purchasing_blank_replacement_rules (
      source_blank_product_id,
      replacement_blank_product_id,
      reason,
      active,
      actor_id
    ) values (
      p_source_blank_product_id,
      p_new_blank_product_id,
      v_reason,
      true,
      v_actor_id
    )
    returning id into v_rule_id;
  end if;

  insert into public.sc_purchasing_row_repair_log (
    source_blank_product_id,
    replacement_blank_product_id,
    unlinked_reservations_moved,
    unlinked_reserved_quantity_moved,
    linked_active_job_items_detected,
    inactive_linked_reservations_skipped,
    source_threshold_before,
    source_threshold_after,
    replacement_threshold_before,
    replacement_threshold_after,
    threshold_moved,
    replacement_rule_id,
    reason,
    actor_id,
    details
  ) values (
    p_source_blank_product_id,
    p_new_blank_product_id,
    v_unlinked_count,
    v_unlinked_quantity,
    v_linked_active_job_item_count,
    v_inactive_linked_count,
    v_source_threshold,
    case when v_threshold_moved then 0 else v_source_threshold end,
    v_target_threshold,
    v_target_threshold_after,
    v_threshold_moved,
    v_rule_id,
    v_reason,
    v_actor_id,
    jsonb_build_object(
      'move_unlinked_reservations_requested', coalesce(p_move_unlinked_reservations, false),
      'move_threshold_requested', coalesce(p_move_threshold, false),
      'remember_rule_requested', coalesce(p_remember_rule, false),
      'physical_inventory_changed', false,
      'inventory_movements_created', false,
      'woo_mapping_changed', false
    )
  )
  returning id into v_audit_id;

  return jsonb_build_object(
    'success', true,
    'audit_id', v_audit_id,
    'source_blank_product_id', p_source_blank_product_id,
    'new_blank_product_id', p_new_blank_product_id,
    'unlinked_reservations_moved', v_unlinked_count,
    'unlinked_reserved_quantity_moved', v_unlinked_quantity,
    'linked_active_job_items_detected', v_linked_active_job_item_count,
    'inactive_linked_reservations_skipped', v_inactive_linked_count,
    'source_threshold_before', v_source_threshold,
    'source_threshold_after', case when v_threshold_moved then 0 else v_source_threshold end,
    'replacement_threshold_before', v_target_threshold,
    'replacement_threshold_after', v_target_threshold_after,
    'threshold_moved', v_threshold_moved,
    'rule_id', v_rule_id,
    'physical_inventory_changed', false,
    'inventory_movements_created', false,
    'woo_mapping_changed', false
  );
end;
$$;

grant execute on function public.sc_purchasing_fix_suggested_item_v1(uuid, uuid, text, boolean, boolean, boolean)
  to anon, authenticated;

notify pgrst, 'reload schema';

commit;
