-- Exact product -> blank mapping reconciliation for already-open work.
--
-- This closes the New Product Line Setup gap without introducing fuzzy identity
-- matching. It only fills currently-null job_items.blank_product_id values when
-- the job item carries an exact Woo ID or exact reusable SKU.
create or replace function public.sc_reconcile_product_mapping_to_open_pullsheet_v1()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_product jsonb;
  v_wp_id text;
  v_sku text;
  v_job record;
begin
  if new.blank_product_id is null
     or new.blank_product_id is not distinct from old.blank_product_id then
    return new;
  end if;

  v_product := to_jsonb(new);
  v_wp_id := nullif(trim(coalesce(
    v_product->>'wp_post_id',
    v_product->>'woocommerce_variation_id',
    v_product->>'woocommerce_product_id',
    ''
  )), '');
  v_sku := nullif(trim(coalesce(v_product->>'sku', '')), '');

  update public.job_items ji
  set blank_product_id = new.blank_product_id
  from public.jobs j
  where j.id = ji.job_id
    and ji.blank_product_id is null
    and coalesce(
      nullif(to_jsonb(ji)->>'inventory_required', '')::boolean,
      true
    )
    and public.sc_purchasing_status_is_active_v1(
      public.sc_purchasing_json_text_v1(to_jsonb(j), 'status')
    )
    and public.sc_purchasing_status_is_active_v1(
      public.sc_purchasing_json_text_v1(to_jsonb(ji), 'status')
    )
    and (
      (
        v_wp_id is not null
        and (
          nullif(trim(coalesce(
            to_jsonb(ji)->>'woocommerce_variation_id',
            ''
          )), '') = v_wp_id
          or (
            nullif(trim(coalesce(
              to_jsonb(ji)->>'woocommerce_variation_id',
              ''
            )), '') is null
            and nullif(trim(coalesce(
              to_jsonb(ji)->>'woocommerce_product_id',
              ''
            )), '') = v_wp_id
          )
        )
      )
      or (
        v_sku is not null
        and v_sku !~* '^MANUAL-[0-9]+-LINE-[0-9]+$'
        and lower(trim(coalesce(
          to_jsonb(ji)->>'order_sku',
          to_jsonb(ji)->>'sku',
          ''
        ))) = lower(v_sku)
      )
    );

  for v_job in
    select distinct ji.job_id
    from public.job_items ji
    join public.jobs j on j.id = ji.job_id
    where ji.blank_product_id = new.blank_product_id
      and public.sc_purchasing_status_is_active_v1(
        public.sc_purchasing_json_text_v1(to_jsonb(j), 'status')
      )
      and public.sc_purchasing_status_is_active_v1(
        public.sc_purchasing_json_text_v1(to_jsonb(ji), 'status')
      )
      and coalesce(
        nullif(to_jsonb(ji)->>'inventory_required', '')::boolean,
        true
      )
      and (
        (
          v_wp_id is not null
          and (
            nullif(trim(coalesce(
              to_jsonb(ji)->>'woocommerce_variation_id',
              ''
            )), '') = v_wp_id
            or (
              nullif(trim(coalesce(
                to_jsonb(ji)->>'woocommerce_variation_id',
                ''
              )), '') is null
              and nullif(trim(coalesce(
                to_jsonb(ji)->>'woocommerce_product_id',
                ''
              )), '') = v_wp_id
            )
          )
        )
        or (
          v_sku is not null
          and v_sku !~* '^MANUAL-[0-9]+-LINE-[0-9]+$'
          and lower(trim(coalesce(
            to_jsonb(ji)->>'order_sku',
            to_jsonb(ji)->>'sku',
            ''
          ))) = lower(v_sku)
        )
      )
  loop
    perform public.sc_repair_pullsheet_purchasing_integrity_v1(
      v_job.job_id,
      null
    );
  end loop;

  return new;
end;
$$;

revoke all on function public.sc_reconcile_product_mapping_to_open_pullsheet_v1()
  from public, anon, authenticated;

drop trigger if exists trg_sc_reconcile_product_mapping_to_open_pullsheet_v1
  on public.products;

create trigger trg_sc_reconcile_product_mapping_to_open_pullsheet_v1
after update of blank_product_id on public.products
for each row
when (
  new.blank_product_id is not null
  and old.blank_product_id is distinct from new.blank_product_id
)
execute function public.sc_reconcile_product_mapping_to_open_pullsheet_v1();

notify pgrst, 'reload schema';

commit;
