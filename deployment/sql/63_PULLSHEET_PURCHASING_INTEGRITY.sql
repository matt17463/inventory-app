-- Returns only the Purchasing adjustment attributable to open inventory-required
-- pull-sheet quantities that are not represented by an active correct reservation.
--
-- The adjustment is calculated against the same authoritative inventory view used
-- by the current v1.4.15 Purchasing client. Existing reservation-backed demand is
-- therefore not duplicated.
create or replace function public.sc_missing_pullsheet_purchasing_demand_v1()
returns table (
  blank_product_id uuid,
  sku_base text,
  name text,
  brand text,
  brand_code text,
  product_type text,
  product_type_code text,
  color text,
  color_code text,
  size text,
  size_code text,
  quantity_on_hand integer,
  reserved_quantity integer,
  available_quantity integer,
  low_stock_threshold integer,
  unit_cost numeric,
  need_to_order integer,
  recommended_order_quantity integer,
  estimated_order_value numeric,
  demand_source_count integer,
  demand_total_quantity integer,
  demand_order_numbers text,
  demand_pullsheet_numbers text,
  demand_sources jsonb,
  integrity_fallback boolean
)
language sql
stable
security definer
set search_path = public
as $$
with line_state as (
  select *
  from public.sc_pullsheet_purchasing_integrity_v1(null) ls
  where ls.inventory_required
    and ls.include_on_purchasing_report
    and ls.blank_product_id is not null
    and ls.unreserved_line_quantity > 0
),
grouped as (
  select
    ls.blank_product_id,
    sum(ls.unreserved_line_quantity)::integer as unreserved_quantity,
    count(*)::integer as source_count,
    string_agg(
      distinct ls.job_id::text,
      ', ' order by ls.job_id::text
    ) as pullsheet_numbers,
    jsonb_agg(
      jsonb_build_object(
        'job_id', ls.job_id,
        'pullsheet_number', ls.job_id,
        'pullsheet_label', 'Pull Sheet #' || ls.job_id::text,
        'job_item_id', ls.job_item_id,
        'quantity', ls.unreserved_line_quantity,
        'item_name', 'Integrity fallback — unrepresented pull-sheet demand',
        'pairing_source', 'pullsheet_purchasing_integrity',
        'pairing_warning',
          case
            when ls.issue_code = 'reservation_repair_available'
              then 'Reservation repair available: stock exists but the pull-sheet quantity is not fully reserved.'
            else 'Integrity fallback: this open pull-sheet quantity is not fully represented by active Purchasing reservations.'
          end
      )
      order by ls.job_id desc, ls.job_item_id desc
    ) as sources
  from line_state ls
  group by ls.blank_product_id
),
inventory_base as (
  select
    g.blank_product_id,
    g.unreserved_quantity,
    g.source_count,
    g.pullsheet_numbers,
    g.sources,
    coalesce(
      public.sc_purchasing_json_numeric_v1(
        to_jsonb(ai),
        'quantity_on_hand',
        'on_hand_quantity',
        'on_hand',
        'total_quantity'
      ),
      0
    )::integer as quantity_on_hand,
    coalesce(
      public.sc_purchasing_json_numeric_v1(
        to_jsonb(ai),
        'reserved_quantity',
        'reserved_units',
        'reserved'
      ),
      0
    )::integer as reserved_quantity,
    coalesce(
      public.sc_purchasing_json_numeric_v1(
        to_jsonb(ai),
        'available_quantity',
        'available_units',
        'available'
      ),
      coalesce(
        public.sc_purchasing_json_numeric_v1(
          to_jsonb(ai),
          'quantity_on_hand',
          'on_hand_quantity',
          'on_hand',
          'total_quantity'
        ),
        0
      )
      -
      coalesce(
        public.sc_purchasing_json_numeric_v1(
          to_jsonb(ai),
          'reserved_quantity',
          'reserved_units',
          'reserved'
        ),
        0
      )
    )::integer as available_quantity,
    bp.sku_base as bp_sku_base,
    bp.name as bp_name,
    coalesce(bp.unit_cost, 0)::numeric as bp_unit_cost,
    coalesce(bp.low_stock_threshold, 0)::integer as bp_threshold,
    br.name as bp_brand,
    br.code as bp_brand_code,
    pt.name as bp_product_type,
    pt.code as bp_product_type_code,
    clr.name as bp_color,
    clr.code as bp_color_code,
    sz.name as bp_size,
    sz.code as bp_size_code
  from grouped g
  join public.blank_products bp on bp.id = g.blank_product_id
  left join public.brands br on br.id = bp.brand_id
  left join public.product_types pt on pt.id = bp.product_type_id
  left join public.colors clr on clr.id = bp.color_id
  left join public.sizes sz on sz.id = bp.size_id
  left join public.sc_purchasing_authoritative_inventory_v3 ai
    on ai.blank_product_id = g.blank_product_id
),
calc as (
  select
    ib.*,
    (
      greatest(
        ib.reserved_quantity
        + ib.unreserved_quantity
        - ib.quantity_on_hand,
        0
      )
      -
      greatest(
        ib.reserved_quantity
        - ib.quantity_on_hand,
        0
      )
    )::integer as shortage_adjustment,
    (
      greatest(
        ib.reserved_quantity
        + ib.unreserved_quantity
        + ib.bp_threshold
        - ib.quantity_on_hand,
        0
      )
      -
      greatest(
        ib.reserved_quantity
        + ib.bp_threshold
        - ib.quantity_on_hand,
        0
      )
    )::integer as recommended_adjustment
  from inventory_base ib
)
select
  calc.blank_product_id,
  calc.bp_sku_base as sku_base,
  calc.bp_name as name,
  calc.bp_brand as brand,
  calc.bp_brand_code as brand_code,
  calc.bp_product_type as product_type,
  calc.bp_product_type_code as product_type_code,
  calc.bp_color as color,
  calc.bp_color_code as color_code,
  calc.bp_size as size,
  calc.bp_size_code as size_code,
  calc.quantity_on_hand,
  calc.reserved_quantity,
  calc.available_quantity,
  calc.bp_threshold as low_stock_threshold,
  calc.bp_unit_cost as unit_cost,
  greatest(calc.shortage_adjustment, 0)::integer as need_to_order,
  greatest(calc.recommended_adjustment, 0)::integer
    as recommended_order_quantity,
  (
    greatest(
      calc.recommended_adjustment,
      calc.shortage_adjustment,
      0
    )::numeric
    * calc.bp_unit_cost
  ) as estimated_order_value,
  calc.source_count as demand_source_count,
  calc.unreserved_quantity as demand_total_quantity,
  calc.pullsheet_numbers as demand_order_numbers,
  calc.pullsheet_numbers as demand_pullsheet_numbers,
  calc.sources as demand_sources,
  true as integrity_fallback
from calc
where calc.shortage_adjustment > 0
   or calc.recommended_adjustment > 0
order by greatest(
           calc.recommended_adjustment,
           calc.shortage_adjustment
         ) desc,
         calc.bp_sku_base;
$$;

