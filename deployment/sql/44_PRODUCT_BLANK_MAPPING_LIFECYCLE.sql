-- Skilled Crafting Inventory v1.2.0
-- Product-to-blank mapping lifecycle
--
-- Additive and idempotent. This migration:
--   * records durable WooCommerce variation/SKU -> blank mappings;
--   * deterministically pairs synced products when Brand/Style/Color/Size has one match;
--   * repairs only currently unpaired pull-sheet lines;
--   * supports safe future-facing substitution of a discontinued blank;
--   * preserves mapping history and does not rewrite already paired job lines.

create extension if not exists pgcrypto;

create or replace function public.sc_mapping_norm_v1(p_value text)
returns text
language sql
immutable
parallel safe
as $$
  select trim(both '-' from regexp_replace(
    lower(translate(coalesce(p_value, ''), '&', ' ')),
    '[^a-z0-9]+', '-', 'g'
  ));
$$;

create table if not exists public.sc_product_blank_mappings (
  id uuid primary key default gen_random_uuid(),
  source_kind text not null check (source_kind in ('woocommerce_variation', 'woocommerce_sku', 'woocommerce_product')),
  source_key text not null,
  source_key_norm text not null,
  blank_product_id uuid not null references public.blank_products(id) on delete restrict,
  is_active boolean not null default true,
  mapping_source text not null default 'manual',
  notes text,
  superseded_at timestamptz,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists sc_product_blank_mappings_active_key_uidx
  on public.sc_product_blank_mappings(source_kind, source_key_norm)
  where is_active;

create index if not exists sc_product_blank_mappings_blank_idx
  on public.sc_product_blank_mappings(blank_product_id)
  where is_active;

create table if not exists public.sc_product_blank_mapping_events (
  id bigint generated by default as identity primary key,
  event_type text not null,
  source_kind text,
  source_key text,
  old_blank_product_id uuid references public.blank_products(id) on delete set null,
  new_blank_product_id uuid references public.blank_products(id) on delete set null,
  mapping_source text,
  notes text,
  affected jsonb not null default '{}'::jsonb,
  actor_id uuid,
  created_at timestamptz not null default now()
);

alter table public.sc_product_blank_mappings enable row level security;
alter table public.sc_product_blank_mapping_events enable row level security;

