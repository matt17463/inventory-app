-- This wrapper checks for an active reservation before calling the existing reserve_inventory RPC.
-- It deliberately refuses to overwrite a mismatched existing reservation.
create or replace function public.sc_ensure_job_item_reservation_v1(
  p_job_id bigint,
  p_job_item_id bigint,
  p_blank_product_id uuid,
  p_quantity integer
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_existing jsonb;
  v_existing_blank text;
  v_existing_quantity integer;
  v_has_status boolean;
  v_has_job_item boolean;
  v_call_result jsonb;
begin
  if p_job_id is null or p_job_item_id is null or p_blank_product_id is null then
    raise exception 'job_id, job_item_id, and blank_product_id are required';
  end if;
  if coalesce(p_quantity, 0) <= 0 then
    raise exception 'quantity must be greater than zero';
  end if;
  if to_regclass('public.inventory_reservations') is null then
    raise exception 'public.inventory_reservations is missing';
  end if;

  select exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'inventory_reservations' and column_name = 'job_item_id'
  ) into v_has_job_item;
  if not v_has_job_item then
    raise exception 'inventory_reservations.job_item_id is missing';
  end if;

  select exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'inventory_reservations' and column_name = 'status'
  ) into v_has_status;

  if v_has_status then
    execute $sql$
      select to_jsonb(r)
      from public.inventory_reservations r
      where r.job_item_id = $1
        and coalesce(lower(r.status::text), 'active') not in ('released', 'cancelled', 'canceled', 'void', 'completed')
      order by r.id desc
      limit 1
    $sql$ into v_existing using p_job_item_id;
  else
    execute $sql$
      select to_jsonb(r)
      from public.inventory_reservations r
      where r.job_item_id = $1
      order by r.id desc
      limit 1
    $sql$ into v_existing using p_job_item_id;
  end if;

  if v_existing is not null then
    v_existing_blank := coalesce(v_existing ->> 'blank_product_id', '');
    v_existing_quantity := coalesce(
      nullif(v_existing ->> 'quantity_reserved', '')::integer,
      nullif(v_existing ->> 'quantity', '')::integer,
      0
    );

    if v_existing_blank <> p_blank_product_id::text or v_existing_quantity <> p_quantity then
      return jsonb_build_object(
        'success', false,
        'action', 'mismatch',
        'needs_review', true,
        'reservation', v_existing,
        'requested_blank_product_id', p_blank_product_id,
        'requested_quantity', p_quantity
      );
    end if;

    return jsonb_build_object(
      'success', true,
      'action', 'existing',
      'needs_review', false,
      'reservation', v_existing
    );
  end if;

  if not exists (
    select 1 from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname = 'reserve_inventory'
  ) then
    raise exception 'public.reserve_inventory is missing';
  end if;

  execute $sql$
    select public.reserve_inventory(
      p_job_id := $1,
      p_job_item_id := $2,
      p_blank_product_id := $3,
      p_quantity := $4
    )
  $sql$ using p_job_id, p_job_item_id, p_blank_product_id, p_quantity;
  v_call_result := null;

  return jsonb_build_object(
    'success', true,
    'action', 'created',
    'needs_review', false,
    'rpc_result', v_call_result
  );
end
$function$;

revoke all on function public.sc_ensure_job_item_reservation_v1(bigint, bigint, uuid, integer) from public, anon, authenticated;
grant execute on function public.sc_ensure_job_item_reservation_v1(bigint, bigint, uuid, integer) to service_role;

comment on function public.sc_ensure_job_item_reservation_v1(bigint, bigint, uuid, integer) is
  'Idempotently ensures one active reservation exists for a mapped job item. Existing mismatches are reported, never overwritten.';

